from pathlib import Path
import ollama

ROOT = Path(r"D:\bug-hunting\hunterflowx")

knowledge = []

# Ambil file penting saja
important_files = [
    "README.md",
    "AGENTS.md",
]

for file in important_files:
    p = ROOT / file
    if p.exists():
        knowledge.append(p.read_text(encoding="utf-8", errors="ignore"))

# Ambil docs dan rules
for folder in ["docs", "rules", "workflow"]:
    fp = ROOT / folder

    if fp.exists():
        for md in fp.rglob("*.md"):
            try:
                knowledge.append(
                    md.read_text(
                        encoding="utf-8",
                        errors="ignore"
                    )[:3000]
                )
            except:
                pass

SYSTEM_PROMPT = f"""
You are HunterFlowX AI.

Follow HunterFlowX methodology.

Core knowledge:

{chr(10).join(knowledge[:20])}

Rules:
- Evidence first
- No vulnerability claims without proof
- Follow HunterFlowX workflow
- Use project documentation as primary source
"""

print("HunterFlowX AI Ready")

while True:
    q = input("\n> ")

    if q.lower() in ["exit", "quit"]:
        break

    response = ollama.chat(
        model="qwen3:4b",
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT
            },
            {
                "role": "user",
                "content": q
            }
        ]
    )

    print("\n")
    print(response["message"]["content"])